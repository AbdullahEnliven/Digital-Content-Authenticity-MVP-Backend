from pathlib import Path
from uuid import uuid4

from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas

from app.core.config import get_settings

settings = get_settings()


def build_certificate_path(verification_id: int) -> Path:
    target = settings.certificate_path / f"verification_{verification_id}"
    target.mkdir(parents=True, exist_ok=True)
    return target / f"certificate_{verification_id}.pdf"


def generate_certificate_pdf(path: Path, payload: dict) -> str:
    c = canvas.Canvas(str(path), pagesize=A4)
    width, height = A4
    c.setTitle("TrustVerify Certificate")
    c.setFont("Helvetica-Bold", 24)
    c.drawString(50, height - 80, "TrustVerify Certificate of Analysis")
    c.setFont("Helvetica", 12)
    lines = [
        f"Verification ID: {payload['verification_id']}",
        f"Verification Code: {payload['verification_code']}",
        f"File Name: {payload['filename']}",
        f"Trust Score: {payload['trust_score']}",
        f"Trust Level: {payload['trust_level']}",
        f"AI Probability: {payload['ai_probability']}%",
        f"Issued At: {payload['issued_at']}",
        f"Reasoning: {payload['reasoning']}",
    ]
    y = height - 130
    for line in lines:
        c.drawString(50, y, line)
        y -= 24
    c.setFont("Helvetica-Oblique", 10)
    c.drawString(50, 60, "Generated by TrustVerify backend")
    c.showPage()
    c.save()
    return str(path)


def new_verification_code() -> str:
    return f"TV-{uuid4().hex[:12].upper()}"
