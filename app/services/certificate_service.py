from pathlib import Path
from uuid import uuid4

from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from app.core.config import get_settings

settings = get_settings()


def build_certificate_path(verification_id: int) -> Path:
    target = settings.certificate_path / f"verification_{verification_id}"
    target.mkdir(parents=True, exist_ok=True)
    return target / f"certificate_{verification_id}.pdf"


def generate_certificate_pdf(path: Path, payload: dict) -> str:
    styles = getSampleStyleSheet()
    primary = colors.HexColor("#112A1E")
    accent = colors.HexColor("#B3945B")
    muted = colors.HexColor("#64748B")
    border = colors.HexColor("#D9E2EC")

    title_style = ParagraphStyle(
        "CertificateTitle",
        parent=styles["Title"],
        fontName="Helvetica-Bold",
        fontSize=26,
        leading=32,
        alignment=1,
        textColor=primary,
        spaceAfter=8,
    )
    subtitle_style = ParagraphStyle(
        "CertificateSubtitle",
        parent=styles["BodyText"],
        fontName="Helvetica",
        fontSize=10,
        leading=15,
        alignment=1,
        textColor=muted,
        spaceAfter=24,
    )
    section_style = ParagraphStyle(
        "CertificateSection",
        parent=styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=12,
        leading=16,
        textColor=accent,
        spaceBefore=12,
        spaceAfter=8,
    )
    label_style = ParagraphStyle(
        "CertificateLabel",
        parent=styles["BodyText"],
        fontName="Helvetica-Bold",
        fontSize=9,
        leading=12,
        textColor=muted,
    )
    value_style = ParagraphStyle(
        "CertificateValue",
        parent=styles["BodyText"],
        fontName="Helvetica",
        fontSize=10.5,
        leading=15,
        textColor=primary,
        wordWrap="CJK",
    )
    reasoning_style = ParagraphStyle(
        "CertificateReasoning",
        parent=value_style,
        fontSize=10,
        leading=15,
    )
    footer_style = ParagraphStyle(
        "CertificateFooter",
        parent=styles["BodyText"],
        fontName="Helvetica-Oblique",
        fontSize=8,
        leading=11,
        alignment=1,
        textColor=muted,
    )

    document = SimpleDocTemplate(
        str(path),
        pagesize=A4,
        rightMargin=0.75 * inch,
        leftMargin=0.75 * inch,
        topMargin=0.7 * inch,
        bottomMargin=0.65 * inch,
        title="TrustVerify Certificate of Authenticity",
    )

    def cell(label: str, value: object) -> list[Paragraph]:
        return [
            Paragraph(label.upper(), label_style),
            Paragraph(str(value or "-"), value_style),
        ]

    details = [
        [cell("Verification ID", payload.get("verification_id")), cell("File Name", payload.get("filename"))],
        [cell("Trust Score", f"{payload.get('trust_score', 0)}%"), cell("Trust Level", payload.get("trust_level"))],
        [cell("AI Probability", f"{payload.get('ai_probability', 0)}%"), cell("Issued At", payload.get("issued_at"))],
    ]

    detail_table = Table(details, colWidths=[3.35 * inch, 3.35 * inch], hAlign="CENTER")
    detail_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
                ("BOX", (0, 0), (-1, -1), 0.8, border),
                ("INNERGRID", (0, 0), (-1, -1), 0.6, border),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("LEFTPADDING", (0, 0), (-1, -1), 12),
                ("RIGHTPADDING", (0, 0), (-1, -1), 12),
                ("TOPPADDING", (0, 0), (-1, -1), 10),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 10),
            ]
        )
    )

    story = [
        Paragraph("Certificate of Authenticity", title_style),
        Paragraph("Generated by TrustVerify after processing the submitted content through the integrated verification pipeline.", subtitle_style),
        detail_table,
        Spacer(1, 18),
        Paragraph("Analysis Summary", section_style),
        Paragraph(payload.get("reasoning") or "Verification completed successfully.", reasoning_style),
        Spacer(1, 26),
        Table(
            [[Paragraph("TrustVerify", label_style), Paragraph("This certificate confirms the recorded analysis result for the referenced content.", value_style)]],
            colWidths=[1.55 * inch, 5.15 * inch],
            style=[
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F6F3EA")),
                ("BOX", (0, 0), (-1, -1), 0.8, colors.HexColor("#E4D8BD")),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("LEFTPADDING", (0, 0), (-1, -1), 12),
                ("RIGHTPADDING", (0, 0), (-1, -1), 12),
                ("TOPPADDING", (0, 0), (-1, -1), 12),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 12),
            ],
        ),
        Spacer(1, 26),
        Paragraph("Generated by TrustVerify backend", footer_style),
    ]

    document.build(story)
    return str(path)


def new_verification_code() -> str:
    return f"TV-{uuid4().hex[:12].upper()}"
